"""
Generate the application icons from the shared brand drawing (`autocorrect.branding`):

- `packaging/autocorrect.ico`   (Windows, multi-size)
- `packaging/autocorrect.icns`  (macOS; Pillow writes ICNS natively, no iconutil needed)
- `packaging/icons/hicolor/<size>x<size>/apps/autocorrect-desktop.png` (Linux freedesktop theme)
- `packaging/typen-mark.svg` / `typen-mark-white.svg` (Syne Bold outlined — matches rasters)
- `packaging/typen-org-avatar.png` (1024×1024 white-tile mark; upload as the GitHub org avatar)

All outputs except the SVG marks and org avatar are build intermediates (git-ignored) and
regenerated by every build script. The same `draw_mark()` renders the live tray icon, so the
.exe, installer, Dock, Start menu and tray can never show different artwork.
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from PIL import Image  # noqa: E402

from autocorrect.branding import FONT_FILENAME, draw_mark  # noqa: E402

ICO_SIZES = [16, 24, 32, 48, 64, 128, 256]
ICNS_SIZES = [16, 32, 64, 128, 256, 512, 1024]
PNG_SIZES = [16, 22, 24, 32, 48, 64, 128, 256, 512]
ORG_AVATAR_SIZE = 1024
MARK_SVG_BLACK = "typen-mark.svg"
MARK_SVG_WHITE = "typen-mark-white.svg"
SQUIGGLE_D = "M20 46 q4 -5 8 0 t8 0 t8 0 t8 0 t8 0 t8 0"


def draw(size: int, *, theme: str = "light") -> Image.Image:
    # App icons default to the light-theme mark (black tile); org avatar uses white.
    return draw_mark(size, theme=theme, active=True)  # type: ignore[arg-type]


def write_ico(out: Path) -> None:
    base = draw(256)
    base.save(
        out, format="ICO", sizes=[(s, s) for s in ICO_SIZES], append_images=[draw(s) for s in ICO_SIZES[:-1]]
    )


def write_icns(out: Path) -> None:
    base = draw(1024)
    base.save(out, format="ICNS", append_images=[draw(s) for s in ICNS_SIZES[:-1]])


def write_pngs(theme_root: Path) -> list[Path]:
    written = []
    for s in PNG_SIZES:
        p = theme_root / "hicolor" / f"{s}x{s}" / "apps" / "autocorrect-desktop.png"
        p.parent.mkdir(parents=True, exist_ok=True)
        draw(s).save(p, format="PNG")
        written.append(p)
    return written


def write_org_avatar(out: Path) -> None:
    # White-tile mark (theme=dark) — default GitHub organisation avatar.
    # Transparent letterbox keeps the rounded tile visible on GitHub's page.
    draw(ORG_AVATAR_SIZE, theme="dark").save(out, format="PNG")


def _syne_bold_letter_paths() -> tuple[str, str, float]:
    """
    Outline Syne Bold \"Aa\" at the same 88x64 mark coords as draw_mark / Brand.tsx.
    Returns (combined_path_d, cursor_start_x, unused) so the SVG never depends on
    a locally installed copy of Syne (which is why a text-based SVG looked wrong).
    """
    try:
        from fontTools.misc.transform import Transform
        from fontTools.pens.svgPathPen import SVGPathPen
        from fontTools.pens.transformPen import TransformPen
        from fontTools.ttLib import TTFont
        from fontTools.varLib.instancer import instantiateVariableFont
    except ImportError as exc:  # pragma: no cover
        raise SystemExit(
            "fonttools is required to outline Syne into packaging/*.svg — "
            "pip install fonttools  (or pip install -e '.[dev]')"
        ) from exc

    font_path = ROOT / "packaging" / "fonts" / FONT_FILENAME
    font = instantiateVariableFont(TTFont(font_path), {"wght": 700})
    upm = font["head"].unitsPerEm
    cmap = font.getBestCmap()
    glyf = font["glyf"]
    hmtx = font["hmtx"]
    scale = 24.0 / upm
    x = 19.75
    baseline = 36.0
    tracking = -1.0
    parts: list[str] = []
    for ch in "Aa":
        name = cmap[ord(ch)]
        width, _lsb = hmtx[name]
        pen = SVGPathPen(glyf)
        # Font y-up → SVG y-down, origin at the text baseline.
        tp = TransformPen(pen, Transform(scale, 0, 0, -scale, x, baseline))
        glyf[name].draw(tp, glyf)
        parts.append(_round_svg_path(pen.getCommands()))
        x += width * scale + tracking
    return " ".join(parts), x, 68.0


def _round_svg_path(d: str, ndigits: int = 3) -> str:
    """Trim float noise from fontTools path commands for stable, readable SVG."""
    import re

    def repl(m: re.Match[str]) -> str:
        return f"{float(m.group(0)):.{ndigits}f}".rstrip("0").rstrip(".")

    return re.sub(r"-?\d+\.\d+", repl, d)


def write_mark_svgs(pk: Path) -> list[Path]:
    letters_d, cursor_start, cursor_end = _syne_bold_letter_paths()
    cursor_w = max(2.0, cursor_end - cursor_start)
    written: list[Path] = []
    variants = (
        (MARK_SVG_BLACK, "#000000", "#ffffff"),
        (MARK_SVG_WHITE, "#ffffff", "#000000"),
    )
    for name, tile, glyph in variants:
        out = pk / name
        out.write_text(
            "\n".join(
                [
                    '<svg xmlns="http://www.w3.org/2000/svg" width="88" height="88" viewBox="0 0 88 88">',
                    "  <!-- Outlined Syne Bold — same drawing as autocorrect.branding.draw_mark. -->",
                    '  <g transform="translate(0 12)">',
                    f'    <rect width="88" height="64" rx="14" fill="{tile}"/>',
                    f'    <path fill="{glyph}" d="{letters_d}"/>',
                    f'    <rect x="{cursor_start:.4f}" y="33" width="{cursor_w:.4f}" height="3" rx="1" fill="{glyph}"/>',
                    f'    <path d="{SQUIGGLE_D}" fill="none" stroke="#e5341a" stroke-width="3.2" stroke-linecap="round"/>',
                    "  </g>",
                    "</svg>",
                    "",
                ]
            ),
            encoding="utf-8",
        )
        written.append(out)
    return written


def main(argv: list[str] | None = None) -> int:
    args = set(argv if argv is not None else sys.argv[1:])
    want_all = not args or "--all" in args
    pk = ROOT / "packaging"
    if want_all or "--ico" in args:
        out = pk / "autocorrect.ico"
        write_ico(out)
        print(f"wrote {out} ({out.stat().st_size} bytes)")
    if want_all or "--icns" in args:
        out = pk / "autocorrect.icns"
        write_icns(out)
        print(f"wrote {out} ({out.stat().st_size} bytes)")
    if want_all or "--png" in args:
        for p in write_pngs(pk / "icons"):
            print(f"wrote {p.relative_to(ROOT)}")
    if want_all or "--svg" in args:
        for p in write_mark_svgs(pk):
            print(f"wrote {p} ({p.stat().st_size} bytes)")
    if want_all or "--org-avatar" in args:
        out = pk / "typen-org-avatar.png"
        write_org_avatar(out)
        print(f"wrote {out} ({out.stat().st_size} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
