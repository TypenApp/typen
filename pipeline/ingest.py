"""
Stage 1: Vocabulary, Frequency, Contraction, Typo, N-Gram, and Domain Pack Ingestion.
Provides the master baseline dataset and supports ingesting external SCOWL / Wordfreq corpora.
"""

from __future__ import annotations

from dataclasses import dataclass, field

from autocorrect.intelligence.schema import CasingFlag, MorphFlag, RegionFlag


@dataclass(slots=True)
class RawWordEntry:
    """Raw lexicon entry before binary compilation."""

    word: str
    log_freq: float
    region_flags: RegionFlag = RegionFlag.UNIVERSAL
    casing_flags: CasingFlag = CasingFlag.LOWER
    morph_mask: MorphFlag = MorphFlag.NONE
    confusion_set_id: int = 0
    exact_casing: str | None = None
    source_count: int = 2


@dataclass(slots=True)
class RawCorpusDataset:
    """Complete structured language intelligence dataset ready for validation & compilation."""

    version: str = "1.1.0"
    released_at: str = "2026-11-02T00:00:00Z"
    words: dict[str, RawWordEntry] = field(default_factory=dict)
    direct_typos: dict[str, tuple[str, float]] = field(default_factory=dict)
    bigrams: list[tuple[str, str, float]] = field(default_factory=list)
    trigrams: list[tuple[str, str, str, float]] = field(default_factory=list)
    abbreviations: set[str] = field(default_factory=set)
    confusion_sets: dict[int, list[str]] = field(default_factory=dict)
    domain_packs: dict[str, dict[str, object]] = field(default_factory=dict)


